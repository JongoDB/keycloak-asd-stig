#!/usr/bin/env python3
"""A software WebAuthn authenticator for the image tests: standard library plus the openssl CLI, no browser.

It builds exactly what a browser hands Keycloak's WebAuthn forms - clientDataJSON, a "none" attestation object, an
assertion signed over authenticatorData || SHA-256(clientDataJSON) - so registration and sign-in can be driven, and
broken on purpose (no user verification, a bad signature, a backwards counter, an algorithm the policy refuses), from
a plain HTTP client. ES256 (P-256) and RS256 (RSA 2048) keys are real and generated by openssl; an "Ed25519"
authenticator only ever registers (a refused algorithm is refused before any signature is checked).

For test containers only: the private keys live in a temporary directory and are deleted with it.
"""
import base64, hashlib, json, os, re, struct, subprocess, tempfile

def b64u(b):
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()

def unb64u(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))

# ---- CBOR (RFC 8949): just what a COSE key and a "none" attestation object need
def _head(major, n):
    if n < 24: return bytes([major << 5 | n])
    if n < 0x100: return bytes([major << 5 | 24, n])
    if n < 0x10000: return bytes([major << 5 | 25]) + struct.pack(">H", n)
    return bytes([major << 5 | 26]) + struct.pack(">I", n)

def cbor(v):
    if isinstance(v, bool): return b"\xf5" if v else b"\xf4"
    if isinstance(v, int): return _head(0, v) if v >= 0 else _head(1, -1 - v)
    if isinstance(v, bytes): return _head(2, len(v)) + v
    if isinstance(v, str): e = v.encode(); return _head(3, len(e)) + e
    if isinstance(v, list): return _head(4, len(v)) + b"".join(cbor(x) for x in v)
    if isinstance(v, dict): return _head(5, len(v)) + b"".join(cbor(k) + cbor(x) for k, x in v.items())
    raise TypeError(type(v))

COSE = {"ES256": -7, "RS256": -257, "Ed25519": -8}

class Authenticator:
    """One credential. alg: ES256 | RS256 | Ed25519 (register-only)."""
    def __init__(self, alg="ES256", workdir=None):
        self.alg, self.counter = alg, 0
        self.dir = workdir or tempfile.mkdtemp(prefix="softauthn-")
        self.key = os.path.join(self.dir, "key-%s.pem" % b64u(os.urandom(6)))
        self.cred_id = os.urandom(32)
        self.user_handle = None
        if alg == "ES256":
            self._ssl("genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", self.key)
        elif alg == "RS256":
            self._ssl("genpkey", "-algorithm", "RSA", "-pkeyopt", "rsa_keygen_bits:2048", "-out", self.key)
        elif alg != "Ed25519":
            raise ValueError(alg)

    def _ssl(self, *args, data=None):
        r = subprocess.run(["openssl"] + list(args), input=data, capture_output=True)
        if r.returncode:
            raise RuntimeError("openssl %s: %s" % (args[0], r.stderr.decode()[-300:]))
        return r.stdout

    def cose_key(self):
        if self.alg == "Ed25519":
            return cbor({1: 1, 3: -8, -1: 6, -2: os.urandom(32)})       # OKP, Ed25519: never signs here
        if self.alg == "ES256":
            der = self._ssl("pkey", "-in", self.key, "-pubout", "-outform", "DER")
            pub = der[-65:]                                              # SubjectPublicKeyInfo ends with 04 || X || Y
            assert pub[0] == 4
            return cbor({1: 2, 3: -7, -1: 1, -2: pub[1:33], -3: pub[33:65]})
        txt = self._ssl("pkey", "-in", self.key, "-text_pub", "-noout").decode()
        mod = re.search(r"Modulus:\s*\n((?:\s+[0-9a-f:]+\n)+)", txt).group(1)
        n = bytes.fromhex(re.sub(r"[\s:]", "", mod)).lstrip(b"\x00")
        e = int(re.search(r"Exponent:\s*(\d+)", txt).group(1))
        return cbor({1: 3, 3: -257, -1: n, -2: e.to_bytes((e.bit_length() + 7) // 8, "big")})

    def sign(self, data):
        return self._ssl("dgst", "-sha256", "-sign", self.key, data=data)

    @staticmethod
    def client_data(kind, challenge_b64u, origin):
        return json.dumps({"type": kind, "challenge": challenge_b64u, "origin": origin, "crossOrigin": False},
                          separators=(",", ":")).encode()

    def register(self, rp_id, challenge_b64u, origin, user_handle_b64u=None, uv=True):
        """The fields of Keycloak's WebAuthn registration form."""
        self.user_handle = unb64u(user_handle_b64u) if user_handle_b64u else None
        flags = 0x01 | (0x04 if uv else 0) | 0x40                        # UP, UV, AT (attested credential data)
        auth = (hashlib.sha256(rp_id.encode()).digest() + bytes([flags]) + struct.pack(">I", self.counter) +
                bytes(16) + struct.pack(">H", len(self.cred_id)) + self.cred_id + self.cose_key())
        cdj = self.client_data("webauthn.create", challenge_b64u, origin)
        att = cbor({"fmt": "none", "attStmt": {}, "authData": auth})
        return {"clientDataJSON": b64u(cdj), "attestationObject": b64u(att), "publicKeyCredentialId": b64u(self.cred_id),
                "authenticatorLabel": "softauthn-%s" % self.alg, "transports": "internal", "error": ""}

    def assert_(self, rp_id, challenge_b64u, origin, uv=True, bad_signature=False, counter=None, user_handle=True):
        """The fields of Keycloak's WebAuthn authentication form (a discoverable credential: userHandle included)."""
        if counter is None:                                              # a forced counter (a clone) leaves ours alone
            self.counter += 1
        flags = 0x01 | (0x04 if uv else 0)
        auth = hashlib.sha256(rp_id.encode()).digest() + bytes([flags]) + struct.pack(">I", self.counter if counter is None else counter)
        cdj = self.client_data("webauthn.get", challenge_b64u, origin)
        sig = self.sign(auth + hashlib.sha256(cdj).digest())
        if bad_signature:
            sig = self.sign(auth + hashlib.sha256(cdj + b" ").digest())     # a valid signature over the wrong data
        return {"clientDataJSON": b64u(cdj), "authenticatorData": b64u(auth), "signature": b64u(sig),
                "credentialId": b64u(self.cred_id),
                "userHandle": b64u(self.user_handle) if (user_handle and self.user_handle) else "", "error": ""}
