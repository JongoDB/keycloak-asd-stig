#!/usr/bin/env python3
"""Generate references/stig-inheritance.md from the IdP skill's control map and STIG rule data.

  python3 scripts/stig_note.py            # rewrite references/stig-inheritance.md
  python3 scripts/stig_note.py --check    # exit 1 if the committed file is out of date (CI)

Every Vuln ID, STIG ID and CAT level in the note comes from keycloak-asd-stig/references/asd-stig-v6r4.json and
control-map.json, never from memory, and every rule is listed individually (no ranges).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKILL = os.path.dirname(HERE)
IDP_REFS = os.path.join(os.path.dirname(SKILL), "keycloak-asd-stig", "references")
OUT = os.path.join(SKILL, "references", "stig-inheritance.md")
CAT = {"I": "CAT I", "II": "CAT II", "III": "CAT III"}


def cell(s, n=None):
    s = (s or "").replace("|", "/").replace("\n", " ").strip()
    return s if n is None or len(s) <= n else s[: n - 3].rstrip() + "..."


def build():
    with open(os.path.join(IDP_REFS, "asd-stig-v6r4.json")) as f:
        stig = json.load(f)
    with open(os.path.join(IDP_REFS, "control-map.json")) as f:
        cmap = json.load(f)["controls"]
    rules = stig["rules"]
    inherited, shared, app, other = [], [], [], {}
    for r in rules:
        c = cmap[r["vuln_id"]]
        row = (r["vuln_id"], r["stig_id"], CAT[r["cat"]], r["title"], c)
        if c["inheritable"] and c["disposition"] in ("KC", "KC-EXT"):
            inherited.append(row)
        elif c["disposition"] == "SHARED":
            shared.append(row)
        elif c["disposition"] == "APP":
            app.append(row)
        else:
            other[c["disposition"]] = other.get(c["disposition"], 0) + 1

    L = ["<!-- Generated by scripts/stig_note.py from keycloak-asd-stig/references (%s, %d rules). "
         "Do not edit by hand. -->" % (stig.get("benchmark", "ASD STIG"), len(rules)), "",
         "# ASD STIG: what your app inherits from the IdP, and what it still owns", "",
         "This is the default split for an application that delegates **all** sign-in to the hardened Keycloak "
         "(authorization code + PKCE through this skill's integration). It does not depend on your app, so you can "
         "plan with it now. For your ATO package, ask the IdP operator for two things: the IdP's own checklist "
         "(`.ckl`/`.cklb` from `kcstig.py verify`) as the inherited evidence, and the inheritance statement for your "
         "client (`kcstig.py inherit --profile <idp profile> --app <client_id>`). That statement is authoritative "
         "for the operator's realm and has the same three groups as the tables below.", "",
         "Rules for writing this up (an assessor will check them):", "",
         "- Cite rules individually, never as ranges. A range silently includes rules the IdP does not satisfy.",
         "- Take IDs and CAT levels from this file or the operator's tool output, not from memory.",
         "- An inherited rule is inherited only while every sign-in goes through the IdP. A local login form, API "
         "key or back door in the app puts the rule back on the app.", "",
         "| Group | Rules | Meaning |", "|---|---|---|",
         "| Inherited from the IdP | %d | Mark inherited; attach the IdP checklist as evidence |" % len(inherited),
         "| Shared | %d | The IdP does its part; the app must do the rest (see the table) |" % len(shared),
         "| Application | %d | The app's own code and design |" % len(app),
         "| Platform / process / conditional | %d | Hosting, procedures, or N/A conditions: neither the IdP nor "
         "app code (%s) |" % (sum(other.values()), ", ".join("%s %d" % kv for kv in sorted(other.items()))), "",
         "## Shared: what the app must still do", "",
         "These are where integrations fail assessments. The integration guide (`integration.md`) implements the "
         "session, logoff, cookie, role, last-logon and logout-connection rows. A few rows name an IdP-operator or "
         "ISSO action instead (unlock procedure, Alt Tokens, CRL refresh, PIV/FICAM scope, audit-log access): those "
         "are the operator's, and the app's checklist points at the IdP's evidence for them. Rows with no specific "
         "action apply the requirement to the app's own sessions, logs, errors and connections.", "",
         "| Vuln | STIG ID | CAT | Requirement | Remaining action |", "|---|---|---|---|---|"]
    for v, sid, cat, title, c in shared:
        L.append("| %s | %s | %s | %s | %s |" % (v, sid, cat, cell(title, 110), cell(c["app_action"] or
                                                   "Implement the requirement for the app's own sessions, logs and errors.")))
    L += ["", "## Application: the app's own code and design (%d)" % len(app), "",
          "Not affected by the IdP. Listed so nothing is assumed inherited.", "",
          "| Vuln | STIG ID | CAT | Requirement |", "|---|---|---|---|"]
    for v, sid, cat, title, c in app:
        L.append("| %s | %s | %s | %s |" % (v, sid, cat, cell(title, 140)))
    L += ["", "## Inherited from the IdP (%d)" % len(inherited), "",
          "Satisfied by the IdP's configuration and verified by its automated checks. Holds only while the app has "
          "no other way in.", "",
          "| Vuln | STIG ID | CAT | Requirement | How the IdP meets it |", "|---|---|---|---|---|"]
    for v, sid, cat, title, c in inherited:
        L.append("| %s | %s | %s | %s | %s |" % (v, sid, cat, cell(title, 110), cell(c["implementation"], 160)))
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("%s is out of date: run scripts/stig_note.py" % OUT, file=sys.stderr)
            return 1
        print("stig-inheritance.md is current")
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
